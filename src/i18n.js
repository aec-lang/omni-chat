export function useI18n() {
  const { settings } = useApp()
  const language = settings.language === 'fa' ? 'fa' : 'en'
  const t = (key) => translations[language][key] || translations.en[key] || key
  return { language, direction: language === 'fa' ? 'rtl' : 'ltr', t }
}
